import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function safeLiteral(source) {
  return JSON.stringify(source)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

export function buildViewer({ htmlSource, coreSource }) {
  const html = safeLiteral(htmlSource);
  const core = safeLiteral(coreSource);
  return `// Generated by apps/script-viewer/tools/build.mjs. Prototype shell only.
;(async () => {
const viewerHtml = ${html};
const embeddedCoreSource = ${core};
const webView = new WebView();
await webView.loadHTML(viewerHtml);
await webView.present();
})();
`;
}

async function main(args) {
  const outputIndex = args.indexOf('--output');
  const outputPath = outputIndex >= 0 ? args[outputIndex + 1] : null;
  if (!outputPath) throw new Error('Usage: node apps/script-viewer/tools/build.mjs --output <path>');
  const [htmlSource, coreSource] = await Promise.all([
    readFile(path.join(appDir, 'viewer.html'), 'utf8'),
    readFile(path.join(appDir, 'core.js'), 'utf8'),
  ]);
  await writeFile(path.resolve(outputPath), buildViewer({ htmlSource, coreSource }), 'utf8');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
